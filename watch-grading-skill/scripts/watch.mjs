#!/usr/bin/env node
// Watch helper: ask the course server whether a sealed take is waiting to
// be graded. No dependencies (Node 18+).
//   node watch.mjs poll
//       Print the poll JSON from GET /w/poll (sent with the poll key):
//       {"pending": n}. This is the cheap yes/no question; the poll hook
//       script asks it every minute and wakes Muse only when n > 0.
//   node watch.mjs pending
//       Print the pending list from GET /w/pending (sent with the grading
//       token): {"takes": [{examId, title, sessionCode, status,
//       sealedAt}]}. Fetching the list claims each take for 15 minutes, so
//       a take listed here is not listed again until the claim expires or
//       a grading upload clears it — grade what it returns, do not fetch
//       it twice to check.
// Credentials come from watch-config.json in the skill folder (one level up
// from this script): {server, token, pollKey}. They are written once, at
// setup, from the teacher's emailed block. Never print them.
// Exit code 0 on success, 1 on any failure (message on stderr).
import { readFileSync } from "node:fs";

const mode = process.argv[2];
if (mode !== "poll" && mode !== "pending") {
  console.error("usage: watch.mjs poll|pending");
  process.exit(1);
}

let config;
try {
  const url = new URL("../watch-config.json", import.meta.url);
  config = JSON.parse(readFileSync(url, "utf8"));
} catch {
  console.error("watch-config.json is missing or unreadable in the skill folder. Run the one-time setup in this skill's SKILL.md first.");
  process.exit(1);
}
const server = String(config.server || "").replace(/\/+$/, "");
const credential = mode === "poll" ? config.pollKey : config.token;
const credentialName = mode === "poll" ? "pollKey" : "token";
if (!server || !credential) {
  console.error("watch-config.json is incomplete: it needs \"server\" and \"" + credentialName + "\". Run the one-time setup in this skill's SKILL.md again.");
  process.exit(1);
}

const header = mode === "poll" ? "X-Poll-Key" : "X-Watch-Token";
let res;
try {
  res = await fetch(server + "/w/" + mode, { headers: { [header]: credential } });
} catch (e) {
  console.error("Could not reach the course server: " + e.message);
  process.exit(1);
}
if (res.status === 401) {
  console.error("The server refused the watch " + (mode === "poll" ? "poll key" : "token") +
    " (401). It was revoked or regenerated by the teacher. Ask the teacher to re-email your watch setup, then run the setup again.");
  process.exit(1);
}
const data = await res.json().catch(() => null);
if (!res.ok || !data) {
  console.error("The course server answered with an error (HTTP " + res.status + ").");
  process.exit(1);
}
console.log(JSON.stringify(data));
