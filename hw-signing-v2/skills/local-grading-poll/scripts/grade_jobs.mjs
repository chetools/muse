#!/usr/bin/env node
// Grading-job helper for the HW Signing v2 grading worker.
// No dependencies (Node 18+).
//
//   node grade_jobs.mjs list
//       Print the pending list from GET /grading/pending as JSON:
//       [{job_id, pkg, kind, created_at, transcript_chars}] — queued
//       jobs and jobs whose claim has expired.
//   node grade_jobs.mjs claim <job_id> --out <claim-file>
//       Claim one job (POST /grading/claim; the claim holds 15
//       minutes). The full claim JSON — package text and transcript —
//       is written to <claim-file>; stdout carries only a short
//       summary. A 409 means another claim already holds the job:
//       the command exits non-zero and writes nothing.
//   node grade_jobs.mjs result <job_id> <result-file>
//       Post a grading result (POST /grading/result). The result file
//       holds the grading sub-agent's structured result:
//       {completeness, accuracy, critique, injection_flags}. The
//       job_id is added by this command. Prints the worker's answer.
//
// Credentials come from config.json in the skill folder (one level up
// from this script): {worker, gradingToken}. The token is sent only as
// the X-Grading-Token header to the configured worker; it is never
// printed, logged, or placed in a URL.
// Exit code 0 on success, 1 on any failure (message on stderr).
import { readFileSync, writeFileSync } from "node:fs";

const USAGE =
  "usage: grade_jobs.mjs list | claim <job_id> --out <claim-file> | " +
  "result <job_id> <result-file>";

const cmd = process.argv[2];
const rest = process.argv.slice(3);

function fail(msg) {
  console.error(msg);
  process.exit(1);
}
if (!cmd) fail(USAGE);

let config;
try {
  config = JSON.parse(
    readFileSync(new URL("../config.json", import.meta.url), "utf8"),
  );
} catch {
  fail(
    "config.json is missing or unreadable in the skill folder. " +
      "Copy config.example.json to config.json and fill in the worker " +
      "address and the grading token.",
  );
}
const worker = String(config.worker || "").replace(/\/+$/, "");
const token = config.gradingToken;
if (!worker || !token) {
  fail(
    'config.json is incomplete: it needs "worker" and "gradingToken". ' +
      "Run the setup in this skill's SKILL.md again.",
  );
}

async function call(method, path, body) {
  let res;
  try {
    res = await fetch(worker + path, {
      method,
      headers: {
        "X-Grading-Token": token,
        ...(body ? { "Content-Type": "application/json" } : {}),
      },
      body: body ? JSON.stringify(body) : undefined,
    });
  } catch (e) {
    fail("Could not reach the grading worker: " + e.message);
  }
  const data = await res.json().catch(() => null);
  return { status: res.status, ok: res.ok, data };
}

function refuse(what, r) {
  if (r.status === 401) {
    fail(
      "The grading worker refused the grading token (401). It was " +
        "revoked or regenerated by the teacher. Ask the teacher to " +
        "re-issue the grading setup, then run the setup again.",
    );
  }
  fail(
    what +
      " failed (HTTP " +
      r.status +
      ")" +
      (r.data && r.data.error ? ": " + r.data.error : "") +
      ".",
  );
}

if (cmd === "list") {
  const r = await call("GET", "/grading/pending");
  if (!r.ok) refuse("Listing pending jobs", r);
  console.log(JSON.stringify(r.data));
} else if (cmd === "claim") {
  const jobId = rest[0];
  const outIdx = rest.indexOf("--out");
  const out = outIdx >= 0 ? rest[outIdx + 1] : null;
  if (!jobId || !out) fail(USAGE);
  const r = await call("POST", "/grading/claim", { job_id: jobId });
  if (r.status === 409) {
    fail(
      "Job " + jobId + " is already claimed by another claim and was " +
        "not claimed here. Skip it; do not retry the claim.",
    );
  }
  if (!r.ok) refuse("Claiming job " + jobId, r);
  writeFileSync(out, JSON.stringify(r.data, null, 2) + "\n", "utf8");
  console.log(
    JSON.stringify({ job_id: jobId, claimed: true, claim_file: out }),
  );
} else if (cmd === "result") {
  const [jobId, file] = rest;
  if (!jobId || !file) fail(USAGE);
  let result;
  try {
    result = JSON.parse(readFileSync(file, "utf8"));
  } catch {
    fail("Cannot read or parse the result file: " + file);
  }
  const r = await call("POST", "/grading/result", {
    ...result,
    job_id: jobId,
  });
  if (!r.ok) refuse("Posting the result for job " + jobId, r);
  console.log(JSON.stringify(r.data));
} else {
  fail(USAGE);
}
