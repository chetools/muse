#!/usr/bin/env python3
"""Browser regression test for the v64 wall fix: stuck audio
from a discarded tile.

The bug (reported 2026-11-27): render() and
renderAttemptTiles() rebuilt the grid by replacing its
innerHTML without pausing, muting or unloading the discarded
<video> elements. A tile that was playing kept playing —
audibly — after it left the document, and neither
claimAudio() nor the stall watchdog could reach it (both
enumerate videos in the document), so hovering another tile
unmuted it on top: two audible videos. Any rebuild while a
tile was audible triggered it; switching "Group by" was the
observed one.

The fix (v64): teardownGridVids() pauses, mutes and unloads
every grid video at the start of render() and
renderAttemptTiles(), before the innerHTML replacement, and
a registry of every video element created (WALLVIDS) lets
claimAudio() and the watchdog sweep elements no longer in
the document.

This harness runs the real app (a scratch copy of this
folder, demo students generated by the app itself) in
headless Chromium and asserts:

  1. A tile is made audible (unmuted and playing).
  2. Switching "Group by" rebuilds the grid: the OLD element
     ends paused, muted and src-less, out of the document,
     and no detached registered element is left playing or
     unmuted.
  3. Hovering a tile of the rebuilt grid leaves exactly one
     video unmuted-and-playing in the whole page state
     (document plus registry).

Run:  python3 tests/wall_regression_v64.py
(needs playwright + a Chromium build; on the Muse machine
that is ~/workspace/.venvs/qa-playwright/bin/python3).
Scratch state goes to a temp folder, or to $WALL_V64_SCRATCH.
"""
import asyncio
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
PORT = 8796
BASE = f"http://127.0.0.1:{PORT}"

FAILURES = []


def report(ok, label, detail=""):
    print(("ok: " if ok else "FAIL: ") + label +
          ((" -- " + detail) if detail else ""), flush=True)
    if not ok:
        FAILURES.append(label)


def http(path, method="GET"):
    req = urllib.request.Request(BASE + path, method=method,
                                 data=b"{}" if method == "POST" else None,
                                 headers={"content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=10) as r:
        return json.loads(r.read().decode())


def start_app(scratch):
    appdir = scratch / "app"
    shutil.copytree(HERE, appdir,
                    ignore=shutil.ignore_patterns(
                        "__pycache__", "config.json", "data"))
    cfg = {"canvas_token": "", "grading_admin_token": "",
           "data_dir": str(scratch / "data")}
    cfgpath = scratch / "config.json"
    cfgpath.write_text(json.dumps(cfg), encoding="utf-8")
    env = dict(os.environ, TEACHER_AUDIT_CONFIG=str(cfgpath),
               TMPDIR=str(scratch))
    proc = subprocess.Popen(
        [sys.executable, "web.py", "--port", str(PORT), "--no-browser"],
        cwd=appdir, env=env,
        stdout=open(scratch / "server.log", "w"),
        stderr=subprocess.STDOUT)
    deadline = time.time() + 30
    while time.time() < deadline:
        try:
            http("/api/status")
            return proc
        except Exception:
            time.sleep(0.5)
    raise RuntimeError("app did not start; see server.log")


def seed_demos():
    http("/api/demos/generate", "POST")
    deadline = time.time() + 240
    while time.time() < deadline:
        try:
            j = http("/api/wall?local=1")
            demos = [s for s in j["students"] if s.get("video_url")]
            if len(demos) >= 8:
                return demos
        except Exception:
            pass
        time.sleep(2)
    raise RuntimeError("demo students did not appear on the wall")


async def run(page):
    await page.goto(BASE + "/wall")
    await page.wait_for_selector("#grid video", timeout=30000)
    await page.wait_for_function(
        "[...document.querySelectorAll('#grid video')]"
        ".every(v => v.readyState >= 2)", timeout=45000)

    # 1. Make the first tile audible: claim it, unmute, play —
    # the state a hover leaves behind.
    await page.evaluate("""() => {
      const v = document.querySelector('#grid video');
      window.__oldTile = v;
      v.muted = false;
      const p = v.play(); if (p) p.catch(()=>{});
    }""")
    await page.wait_for_function(
        "window.__oldTile && !window.__oldTile.paused "
        "&& !window.__oldTile.muted", timeout=15000)
    report(True, "first tile is unmuted and playing before "
                 "the rebuild")

    # 2. Switch Group by: render() rebuilds the grid.
    await page.evaluate("""() => {
      const g = document.getElementById('fgroup');
      g.value = 'course';
      g.dispatchEvent(new Event('change'));
    }""")
    await page.wait_for_function(
        "window.__oldTile && !window.__oldTile.isConnected",
        timeout=15000)
    await page.wait_for_timeout(700)
    old = await page.evaluate("""() => {
      const v = window.__oldTile;
      return {paused: v.paused, muted: v.muted,
              srcAttr: v.getAttribute('src'),
              connected: v.isConnected};
    }""")
    report(old["paused"] and old["muted"] and old["srcAttr"] is None
           and not old["connected"],
           "the discarded tile is paused, muted and src-less "
           "after the Group by rebuild", json.dumps(old))
    audible = await page.evaluate("""() => {
      let n = 0;
      document.querySelectorAll('video').forEach(v => {
        if (!v.paused && !v.muted) n++; });
      WALLVIDS.forEach(v => {
        if (!v.isConnected && !v.paused && !v.muted) n++; });
      return n;
    }""")
    report(audible == 0,
           "no video is unmuted-and-playing after the rebuild "
           "(document plus registry)", f"audible={audible}")

    # 3. Hover a tile of the rebuilt grid: exactly one audible
    # video in the whole page state.
    await page.hover("#grid .tile video")
    await page.wait_for_timeout(1200)
    audible = await page.evaluate("""() => {
      let n = 0;
      document.querySelectorAll('video').forEach(v => {
        if (!v.paused && !v.muted) n++; });
      WALLVIDS.forEach(v => {
        if (!v.isConnected && !v.paused && !v.muted) n++; });
      return n;
    }""")
    report(audible == 1,
           "hovering a rebuilt tile leaves exactly one video "
           "unmuted-and-playing", f"audible={audible}")


async def main():
    try:
        from playwright.async_api import async_playwright
    except ImportError:
        print("SKIP: playwright is not installed")
        return 3
    scratch = Path(os.environ.get("WALL_V64_SCRATCH") or
                   tempfile.mkdtemp(prefix="wall-v64-"))
    scratch.mkdir(parents=True, exist_ok=True)
    proc = start_app(scratch)
    try:
        seed_demos()
        async with async_playwright() as pw:
            b = await pw.chromium.launch(
                args=["--autoplay-policy=no-user-gesture-required",
                      "--media-cache-size=0",
                      "--disk-cache-size=0"])
            page = await b.new_page(viewport={"width": 1500,
                                              "height": 950})
            page.on("console", lambda m: print(
                "CONSOLE:", m.type, m.text[:160], flush=True))
            await run(page)
            await page.screenshot(
                path=str(scratch / "wall-v64-final.png"))
            await b.close()
    finally:
        proc.terminate()
    if FAILURES:
        print(f"WALL V64 REGRESSION: FAIL ({len(FAILURES)})")
        return 1
    print("WALL V64 REGRESSION: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
