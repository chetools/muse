    try:
        from playwright.async_api import async_playwright
    except ImportError:
        print("SKIP: playwright is not installed")
        return 3
    scratch = Path(os.environ.get("WALL_V60_SCRATCH") or
                   tempfile.mkdtemp(prefix="wall-v61-"))
    scratch.mkdir(parents=True, exist_ok=True)
    proc = start_app(scratch)
    try:
        seed_demos()
        async with async_playwright() as pw:
            b = await pw.chromium.launch(
                args=["--autoplay-policy=no-user-gesture-required",
                      # The stall phases must know that a seek
                      # to an unbuffered position needs the
                      # network they hold: with the media and
                      # disk caches at their defaults, these
                      # small local demo files are soon served
                      # from cache instead, and whether a given
                      # seek stalls varies from run to run.
                      "--media-cache-size=0",
                      "--disk-cache-size=0"])
            page = await b.new_page(viewport={"width": 1500,
                                              "height": 950})
            page.on("console", lambda m: print(
                "CONSOLE:", m.type, m.text[:160], flush=True))
            await run(page)
            await page.screenshot(
                path=str(scratch / "wall-v61-final.png"))
            await b.close()
    finally:
        proc.terminate()
    if FAILURES:
        print(f"WALL V61 REGRESSION: FAIL ({len(FAILURES)})")
        return 1
    print("WALL V61 REGRESSION: PASS")
    return 0


