import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
PORT = 8794
BASE = f"http://127.0.0.1:{PORT}"

ZV_STATE_JS = """() => { const v = document.getElementById('zv');
  let px = null;
  try {
    const c = document.createElement('canvas'); c.width = 32; c.height = 18;
    const g = c.getContext('2d'); g.drawImage(v, 0, 0, 32, 18);
    const d = g.getImageData(0, 0, 32, 18).data;
    let sum = 0, n = 0;
    for (let i = 0; i < d.length; i += 4) { sum += d[i] + d[i+1] + d[i+2]; n++; }
    px = Math.round(sum / n * 10) / 10;
  } catch (e) { px = -1; }
  return {rs: v.readyState, t: Math.round(v.currentTime*10)/10,
          dur: Math.round((v.duration||0)*10)/10, seeking: v.seeking,
          paused: v.paused, px}; }"""

STATE_JS = """() => [...document.querySelectorAll('#grid video')].map(v => {
  let px = null;
  try {
    const c = document.createElement('canvas'); c.width = 32; c.height = 18;
    const g = c.getContext('2d'); g.drawImage(v, 0, 0, 32, 18);
    const d = g.getImageData(0, 0, 32, 18).data;
    let sum = 0, n = 0;
    for (let i = 0; i < d.length; i += 4) { sum += d[i] + d[i+1] + d[i+2]; n++; }
    px = Math.round(sum / n * 10) / 10;
  } catch (e) { px = -1; }
  return {rs: v.readyState, t: Math.round(v.currentTime*10)/10,
          dur: Math.round((v.duration||0)*10)/10, seeking: v.seeking,
          paused: v.paused, px};
})"""

FAILURES = []


def report(ok, label, detail=""):
    print(("ok: " if ok else "FAIL: ") + label +
          ((" -- " + detail) if detail else ""), flush=True)
    if not ok:
        FAILURES.append(label)


def http(path, method="GET"):
    req = urllib.request.Request(BASE + path, method=method,
                                 data=b"{}" if method == "POST" else None,
                                 headers={"content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=10) as r:
        return json.loads(r.read().decode())


def start_app(scratch):
    appdir = scratch / "app"
    shutil.copytree(HERE, appdir,
                    ignore=shutil.ignore_patterns(
                        "__pycache__", "config.json", "data"))
    cfg = {"canvas_token": "", "grading_admin_token": "",
           "data_dir": str(scratch / "data")}
    cfgpath = scratch / "config.json"
    cfgpath.write_text(json.dumps(cfg), encoding="utf-8")
    env = dict(os.environ, TEACHER_AUDIT_CONFIG=str(cfgpath),
               TMPDIR=str(scratch))
    proc = subprocess.Popen(
        [sys.executable, "web.py", "--port", str(PORT), "--no-browser"],
        cwd=appdir, env=env,
        stdout=open(scratch / "server.log", "w"),
        stderr=subprocess.STDOUT)
    deadline = time.time() + 30
    while time.time() < deadline:
        try:
            http("/api/status")
            return proc
        except Exception:
            time.sleep(0.5)
    raise RuntimeError("app did not start; see server.log")


def seed_demos():
    http("/api/demos/generate", "POST")
    deadline = time.time() + 240
    while time.time() < deadline:
        try:
            j = http("/api/wall?local=1")
            demos = [s for s in j["students"] if s.get("video_url")]
            if len(demos) >= 8:
                return demos
        except Exception:
            pass
        time.sleep(2)
    raise RuntimeError("demo students did not appear on the wall")


async def wait_tiles(page, bound_s, label):
    """Poll until every tile has a frame; return (ok, states, waited)."""
    t0 = time.time()
    last = []
    while time.time() - t0 < bound_s:
        last = await page.evaluate(STATE_JS)
        if last and all(s["rs"] >= 2 and isinstance(s["px"], (int, float))
                        and s["px"] > 0 for s in last):
            return True, last, time.time() - t0
        await page.wait_for_timeout(500)
    return False, last, time.time() - t0


async def clear_http_cache(page):
    # The demo files are small enough for the browser to
    # cache whole: a seek the harness means to stall at the
    # network can otherwise complete from the HTTP cache
    # without any request reaching the interception. The
    # stall phases clear the cache first, so their seeks
    # genuinely need the network they then hold.
    try:
        ses = await page.context.new_cdp_session(page)
        await ses.send("Network.enable")
        await ses.send("Network.clearBrowserCache")
        await ses.detach()
    except Exception:
        pass


async def zoom_scrub_back(page, frac):
    await page.evaluate("document.querySelector('.tile').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    await page.wait_for_function(
        "document.getElementById('zv').duration > 0", timeout=20000)
    await page.evaluate("""(f) => { const zv = document.getElementById('zv');
      return new Promise(res => {
        zv.addEventListener('seeked', () => res('seeked'), {once: true});
        zv.currentTime = f * zv.duration;
        setTimeout(() => res('timeout'), 10000); }); }""", frac)
    await page.evaluate(
        "document.getElementById('zv').play().catch(()=>{})")
    await page.wait_for_timeout(900)
    await page.evaluate("document.getElementById('backbtn').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")


async def run(page):
    await page.goto(BASE + "/wall")
    await page.wait_for_selector("#grid video", timeout=30000)
    ok, st, waited = await wait_tiles(page, 45, "initial")
    report(ok, f"initial wall paints every tile ({waited:.1f} s)",
           json.dumps(st))

    # 1. Three zoom -> scrub -> Back cycles.
    for i, frac in enumerate((0.5, 0.25, 0.7), 1):
        await zoom_scrub_back(page, frac)
        ok, st, waited = await wait_tiles(page, 25, f"cycle {i}")
        report(ok, f"cycle {i}: zoom -> scrub {frac} -> Back, every "
                   f"tile framed within 25 s ({waited:.1f} s)",
               json.dumps(st))

    # The tile used for the stall phases: not the followed tile.
    idx = 2
    fname = await page.evaluate(
        f"document.querySelectorAll('#grid video')[{idx}]"
        ".src.split('/').pop()")

    def deep_hold(holds, seconds):
        # Holds the first request whose Range starts deep in
        # the file — a far seek's own fetch. The initial
        # bytes=0- fetch passes, and the watchdog's re-issued
        # seek is the second deep request and passes too.
        async def handler(route):
            rng = route.request.headers.get("range", "")
            deep = False
            if rng.startswith("bytes="):
                try:
                    deep = int(rng[6:].split("-")[0] or 0) > 65536
                except ValueError:
                    deep = False
            if deep and holds.get("live") \
                    and not holds["used"]:
                holds["used"] = True
                await asyncio.sleep(seconds)
                try:
                    await route.continue_()
                except Exception:
                    pass
                return
            await route.continue_()
        return handler

    def all_hold(holds, seconds):
        # Holds EVERY request to the file while the hold is
        # live. A far seek on a drained, framed element can
        # then get its data from nowhere else. The phase
        # disarms (live=False) once the stall is confirmed,
        # so the watchdog's re-issued seek or reload — the
        # recovery under test — passes.
        async def handler(route):
            if holds.get("live"):
                holds["seen"] = holds.get("seen", 0) + 1
                await asyncio.sleep(seconds)
                try:
                    await route.continue_()
                except Exception:
                    pass
                return
            await route.continue_()
        return handler

    # 2. A held seek request after a return: the watchdog must
    # re-issue the seek and recover the tile without a reload.
    # The hold (45 s) far outlasts the recovery bound (30 s),
    # so recovery can only come from the re-issued seek's own
    # request, never from the held request completing.
    hold = {"used": False, "live": False, "seen": 0}
    hold_handler = all_hold(hold, 45)
    await page.route(f"**/media/demo/{fname}", hold_handler)
    await page.evaluate("document.querySelector('.tile').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    await page.wait_for_function(
        "document.getElementById('zv').duration > 0", timeout=20000)
    await page.evaluate("""() => { const z =
      document.getElementById('zseek');
      z.value = 0.97; z.dispatchEvent(new Event('input')); }""")
    await page.evaluate(
        f"document.querySelectorAll('#grid video')[{idx}]"
        ".pause()")
    hold["live"] = True
    await page.click("#backbtn")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    await page.wait_for_timeout(1200)
    st = (await page.evaluate(STATE_JS))[idx]
    if not (st["seeking"] and st["rs"] < 2):
        # The scrub's seek got its data without the held
        # network (the tile's buffer, or a download still
        # in flight): reload the tile with the hold off,
        # then seek it with the hold live — the stall
        # under test is the same.
        hold["live"] = False
        await clear_http_cache(page)
        await page.evaluate(
            f"document.querySelectorAll('#grid video')[{idx}]"
            ".load()")
        await page.wait_for_function(
            f"document.querySelectorAll('#grid video')[{idx}]"
            ".duration > 0", timeout=20000)
        hold["live"] = True
        await page.evaluate(
            f"seekFrac(document.querySelectorAll('#grid video')"
            f"[{idx}], 0.97)")
        await page.wait_for_timeout(1200)
        st = (await page.evaluate(STATE_JS))[idx]
    report(st["seeking"] and st["rs"] < 2,
           "held seek leaves the tile in the stalled state "
           "(seeking, readyState < 2)", json.dumps(st))
    hold["live"] = False
    ok, st, waited = await wait_tiles(page, 30, "stall recovery")
    one = st[idx] if len(st) > idx else {}
    report(ok and one.get("rs", 0) >= 2 and one.get("px", 0) > 0,
           f"watchdog recovers the stalled tile without a reload "
           f"({waited:.1f} s)", json.dumps(one))
    await page.unroute(f"**/media/demo/{fname}", hold_handler)

    # 3. Play pressed during a seek that never completes: the
    # time-boxed wait must still issue play(). The stall is
    # made deterministic by construction: a paused tile is
    # reloaded, and the first request whose Range starts
    # deep in the file — the seek's own fetch — is held.
    # (Choosing a target outside the buffered ranges is not
    # enough on its own: these small demo files are soon
    # buffered whole, as the buffered-state probe recorded
    # in this file's scratch runs showed.)
    idx3 = await page.evaluate("""() => {
      const vs = document.querySelectorAll('#grid video');
      let best = -1;
      for (let i = 0; i < vs.length; i++)
        if (vs[i].paused && vs[i].duration
            && (best < 0
                || vs[i].duration > vs[best].duration))
          best = i;
      return best; }""")
    report(idx3 >= 0, "play phase: a paused tile exists",
           json.dumps(idx3))
    fname3 = await page.evaluate(
        f"document.querySelectorAll('#grid video')[{idx3}]"
        ".src.split('/').pop()")
    hold3 = {"used": False, "live": False}
    h3 = deep_hold(hold3, 30)
    await page.route(f"**/media/demo/{fname3}", h3)
    await page.evaluate(
        f"document.querySelectorAll('#grid video')[{idx3}].load()")
    await page.wait_for_function(
        f"document.querySelectorAll('#grid video')[{idx3}]"
        ".duration > 0", timeout=20000)
    hold3["live"] = True
    await page.evaluate("""(a) => {
      window.__playCalls = [];
      const proto = HTMLMediaElement.prototype;
      if (!proto.__v60wrapped) { proto.__v60wrapped = true;
        const orig = proto.play;
        proto.play = function () { window.__playCalls.push(
          this.src.split('/').pop()); return orig.call(this); }; }
      const v = document.querySelectorAll('#grid video')[a.i];
      seekFrac(v, a.f); playTile(v); }""",
                        {"i": idx3, "f": 0.98})
    await page.wait_for_timeout(1500)
    st = (await page.evaluate(STATE_JS))[idx3]
    report(st["seeking"] and st["rs"] < 2,
           "the play phase's seek is genuinely stalled "
           "(seeking, readyState < 2)", json.dumps(st))
    await page.wait_for_timeout(1300)
    calls = await page.evaluate("window.__playCalls")
    st = (await page.evaluate(STATE_JS))[idx3]
    report(fname3 in calls and st["seeking"],
           "play() is issued for the stalled tile within the "
           "time-box, while its seek is still incomplete",
           f"playCalls={calls} state={json.dumps(st)}")
    await page.unroute(f"**/media/demo/{fname3}", h3)

    # 4. (v61) The zoom video's own stalled seek: the first
    # deep-range request to its file after arming — the
    # seek's fetch — is held; the watchdog must recover the
    # zoom video framed and playing (its re-issued seek is
    # the second deep request and passes).
    # The zoom phase uses the FIRST tile's file — the
    # largest demo: it exceeds the renderer's media cache,
    # so a far seek on the zoom video genuinely needs the
    # network (the smaller files are soon cached whole in
    # the renderer and their seeks complete without one).
    zfile = await page.evaluate("""() => {
      const vs = document.querySelectorAll('#grid video');
      return vs[0].src.split('/').pop(); }""")
    zhold = {"used": False, "live": False, "seen": 0}
    hz = all_hold(zhold, 45)
    await page.route(f"**/media/demo/{zfile}", hz)
    await page.locator(".tile").nth(0).click()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    await page.wait_for_function(
        "document.getElementById('zv').duration > 0", timeout=20000)
    await page.evaluate(
        "document.getElementById('zv').play().catch(()=>{})")
    await page.wait_for_timeout(800)
    # Pause and let the in-flight download drain, so the
    # seek below cannot ride it to the target.
    await page.evaluate("document.getElementById('zv').pause()")
    last_end = -1
    for _ in range(12):
        await page.wait_for_timeout(500)
        end = await page.evaluate("""() => { const v =
          document.getElementById('zv');
          return v.buffered.length ? v.buffered.end(
            v.buffered.length - 1) : 0; }""")
        if end == last_end:
            break
        last_end = end
    zdur = await page.evaluate(
        "document.getElementById('zv').duration")
    zs = {"seeking": False, "rs": 4}
    if last_end < zdur - 0.5:
        zhold["live"] = True
        await page.evaluate("""() => { const zv =
          document.getElementById('zv');
          zv.currentTime = 0.97 * zv.duration;
          playAfterSeek(zv); }""")
        await page.wait_for_timeout(1200)
        zs = await page.evaluate(ZV_STATE_JS)
    if not (zs["seeking"] and zs["rs"] < 2):
        # The seek was served from the buffer or the cache:
        # clear the cache, reload the zoom video with the
        # hold off, then seek it with the hold live.
        zhold["live"] = False
        await clear_http_cache(page)
        await page.evaluate("document.getElementById('zv').load()")
        await page.wait_for_function(
            "document.getElementById('zv').duration > 0",
            timeout=20000)
        zhold["live"] = True
        await page.evaluate("""() => { const zv =
          document.getElementById('zv');
          zv.currentTime = 0.97 * zv.duration;
          playAfterSeek(zv); }""")
        await page.wait_for_timeout(1200)
        zs = await page.evaluate(ZV_STATE_JS)
    report(zs["seeking"] and zs["rs"] < 2,
           "zoom phase: the held seek leaves the zoom video "
           "stalled (seeking, readyState < 2)", json.dumps(zs))
    zhold["live"] = False
    t0 = time.time(); zs = {}
    while time.time() - t0 < 30:
        zs = await page.evaluate(ZV_STATE_JS)
        if zs["rs"] >= 2 and zs["px"] and zs["px"] > 0:
            break
        await page.wait_for_timeout(500)
    report(zs.get("rs", 0) >= 2 and zs.get("px", 0) > 0
           and zs.get("paused") is False,
           f"watchdog recovers the zoom video framed and "
           f"playing ({time.time()-t0:.1f} s)", json.dumps(zs))
    await page.unroute(f"**/media/demo/{zfile}", hz)
    await page.evaluate("document.getElementById('backbtn').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    ok, st, waited = await wait_tiles(page, 25, "post-zoom")
    report(ok, f"wall framed after the zoom stall phase "
               f"({waited:.1f} s)", json.dumps(st))

    # 5. (v61) The wall's one playing tile, stalled by a
    # whole-wall scrub: hover-play a tile, hold the first
    # deep-range request to its file, scrub all — it must
    # come back framed AND playing.
    idx = 1
    fname5 = await page.evaluate(
        f"document.querySelectorAll('#grid video')[{idx}]"
        ".src.split('/').pop()")
    box = await page.locator("#grid .tile").nth(idx).bounding_box()
    await page.mouse.move(box["x"] + box["width"] / 2,
                          box["y"] + 40)
    await page.wait_for_function(
        f"!document.querySelectorAll('#grid video')[{idx}].paused",
        timeout=15000)
    hold5 = {"used": False, "live": False}
    h5 = deep_hold(hold5, 45)
    await page.route(f"**/media/demo/{fname5}", h5)
    hold5["live"] = True
    await page.evaluate("setFracAll(0.62)")
    await page.wait_for_timeout(1200)
    st5 = (await page.evaluate(STATE_JS))[idx]
    report(st5["seeking"] and st5["rs"] < 2,
           "wall phase: the scrub stalls the playing tile's "
           "seek (seeking, readyState < 2)", json.dumps(st5))
    t0 = time.time(); st5 = {}
    while time.time() - t0 < 30:
        st5 = (await page.evaluate(STATE_JS))[idx]
        if st5["rs"] >= 2 and st5["px"] and st5["px"] > 0 \
                and st5["paused"] is False:
            break
        await page.wait_for_timeout(500)
    report(st5.get("rs", 0) >= 2 and st5.get("px", 0) > 0
           and st5.get("paused") is False,
           f"the playing tile recovers framed and still "
           f"playing ({time.time()-t0:.1f} s)", json.dumps(st5))
    await page.unroute(f"**/media/demo/{fname5}", h5)
    await page.mouse.move(10, 10)
    # 6. (v61) Browser history: Back closes the zoom view
    # onto the live wall, on every entry path.
    await page.evaluate("document.querySelector('.tile').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    hstate = await page.evaluate("history.state")
    report(bool(hstate and hstate.get("zoom")),
           "opening the zoom view pushed a history entry",
           json.dumps(hstate))
    await page.go_back()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    ok, st, waited = await wait_tiles(page, 25, "history back")
    report(ok and await page.evaluate("location.pathname")
           == "/wall",
           f"browser Back returns to the live wall, tiles "
           f"framed ({waited:.1f} s)", json.dumps(st))
    await page.go_forward()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    report(True, "browser Forward reopens the zoom view")
    await page.go_back()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    # The in-page button takes the same path.
    await page.evaluate("document.querySelector('.tile').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    await page.evaluate("document.getElementById('backbtn').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    report(await page.evaluate("location.pathname") == "/wall",
           "the Back to wall button closes the zoom view on "
           "the same history path")
    # Entry from the dashboard (the teacher's "sometimes"):
    # one Back from the zoom must land on the wall, not on
    # the submissions page.
    await page.goto(BASE + "/")
    await page.click('a[href="/wall"]')
    await page.wait_for_selector("#grid video", timeout=30000)
    ok, st, waited = await wait_tiles(page, 45, "via dashboard")
    await page.evaluate("document.querySelector('.tile').click()")
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'")
    await page.go_back()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    report(await page.evaluate("location.pathname") == "/wall",
           "from the dashboard: one browser Back from the "
           "zoom lands on the wall, not the submissions page")
    # Entry by focus deep link (the table's student links).
    students = http("/api/wall?local=1")["students"]
    fid = next(s["id"] for s in students if s.get("video_url"))
    await page.goto(BASE + "/wall?focus=" + fid)
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'block'",
        timeout=30000)
    await page.go_back()
    await page.wait_for_function(
        "document.getElementById('zoom').style.display === 'none'")
    report(await page.evaluate("location.pathname") == "/wall",
           "from a focus deep link: browser Back closes the "
           "zoom onto the wall instead of leaving the page")

    # 7. (v61) The Activity panel starts blank on page load;
    # lines from work done in the session appear.
    await page.goto(BASE + "/")
    await page.wait_for_selector("#activitylog", timeout=15000)
    await page.wait_for_timeout(4500)
    n0 = await page.evaluate(
        "document.getElementById('activitylog').children.length")
    report(n0 == 0, "the Activity panel starts blank on page "
           "load, with the app's earlier lines unreplayed",
           f"children={n0}")
