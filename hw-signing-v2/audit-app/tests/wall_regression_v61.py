#!/usr/bin/env python3
"""Browser regression test for the v61 audit-app fixes,
keeping the v60 video-wall phases. (The v60 docstring follows.)

v61 adds, from the teacher's 2026-11-26 report:

  4. The zoom video's own stall: a seek of the zoom video
     whose range request is held must be recovered by the
     stall watchdog (which until v61 watched only wall
     tiles), and a zoom video that was playing resumes.
  5. The wall's one playing tile, stalled by a whole-wall
     scrub (setFracAll) whose seek request is held, is
     recovered framed AND playing, not paused black.
  6. Browser history: opening the zoom view pushes a
     history entry, so one browser Back closes the zoom
     view onto the (live) wall — from a tile click, from
     the dashboard link, and from a focus deep link — and
     Forward reopens it; the Back to wall button takes the
     same path.
  7. The dashboard Activity panel starts blank on page
     load (earlier lines are never replayed into it), and
     lines from work done in the session appear.

The v60 phases, kept:

Browser regression test for the v60 video-wall fix.

The bug (diagnosed 2026-11-26, wall-repro-scratch/FINDINGS.md):
after wall -> zoom, scrub, Back, every tile came back black at
0% . 0:00 and refused to play; only a reload recovered. Three
causes: Back rebuilt the wall (innerHTML), discarding every
tile's decoded frame and buffers; recovery was one burst seek
per tile with no retry; and both recovery paths excluded a
tile stuck IN a seek (reviveStalledTiles returned early for
seeking, playAfterSeek waited for a 'seeked' that never came).

This harness runs the real app (a scratch copy of this folder,
demo students generated by the app itself) in headless
Chromium and asserts:

  1. Three consecutive zoom -> scrub -> Back cycles: after
     each return, every tile reaches readyState >= 2 with a
     non-black frame (canvas pixel mean > 0) within a stated
     bound, with no reload.
  2. A tile whose seek range request is deliberately held by
     request interception after a return (a stalled seek:
     seeking stays true, readyState < 2) is recovered by the
     stall watchdog's re-issued seek, without a reload.
  3. With a tile's seeks held indefinitely, pressing play on
     the stalled tile still issues play() (the time-boxed
     playAfterSeek path) instead of waiting for ever.

Run:  python3 tests/wall_regression_v61.py
Scratch state goes to a temp folder, or to $WALL_V61_SCRATCH.
"""
